use vtpu_runtime::base256;

macro_rules! b256_test {
    ($name:ident, $byte:expr) => {
        #[test] fn $name() {
            let encoded = base256::encode_byte($byte);
            let decoded = base256::decode_syllable(&encoded);
            assert_eq!(decoded, Some($byte));
        }
    }
}

