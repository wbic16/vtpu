#!/usr/bin/env bash
# vTPU KPI Measurement Script — R23W4
# Runs benchmarks, parses output, generates markdown dashboard

set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
VTPU_ROOT="$(cd "$SCRIPT_DIR/.." && pwd)"
BENCH_DIR="$VTPU_ROOT/benchmarks/cache"
OUTPUT_FILE="$VTPU_ROOT/docs/KPI-DASHBOARD.md"

echo "==> vTPU KPI Measurement (R23W4)"
echo "==> Running benchmarks..."

# Build benchmarks if needed
if [[ ! -f "$BENCH_DIR/sequential_access" ]]; then
    echo "==> Building cache benchmarks..."
    (cd "$BENCH_DIR" && make clean && make)
fi

# Run micro-benchmark
echo "==> Running micro-benchmark (Rust)..."
(cd "$VTPU_ROOT" && cargo build --quiet --example micro_bench 2>/dev/null || true)
MICRO_OUTPUT=$("$VTPU_ROOT/target/debug/examples/micro_bench" 2>&1 || echo "FAILED")

# Run cache benchmarks
echo "==> Running cache benchmarks (C)..."
SEQ_OUTPUT=$("$BENCH_DIR/sequential_access" 2>&1)
RAND_OUTPUT=$("$BENCH_DIR/random_access" 2>&1)
COORD_OUTPUT=$("$BENCH_DIR/coordinate_patterns" 2>&1)

# Parse results
BALANCED_OPS_CYCLE=$(echo "$MICRO_OUTPUT" | grep -A3 "Balanced" | grep "Ops/cycle" | awk '{print $2}')
L1_SEQ_CYCLES=$(echo "$SEQ_OUTPUT" | grep "L1.*cycles/element" | awk '{print $6}')
L1_RAND_CYCLES=$(echo "$RAND_OUTPUT" | grep "L1.*cycles/access" | awk '{print $6}')

# Generate dashboard
cat > "$OUTPUT_FILE" <<EOF
# vTPU KPI Dashboard

**Last Updated:** $(date -u +"%Y-%m-%d %H:%M UTC")  
**Rally:** R23 Wave 4  
**Machine:** logos-prime (AMD R9 8945HS, 96GB RAM)

---

## Core Metrics

### Ops/Cycle (North Star KPI)

| Workload | Current | Target | Status |
|----------|---------|--------|--------|
| Balanced (33/33/33) | ${BALANCED_OPS_CYCLE:-N/A} | 3.0 | $(if [[ "${BALANCED_OPS_CYCLE:-0}" == "3.00" ]]; then echo "🟢 AT TARGET"; else echo "🟡 BELOW"; fi) |
| D-Heavy (80/10/10) | - | 2.5 | 🔴 Not measured |
| S-Heavy (10/80/10) | - | 2.5 | 🔴 Not measured |

**Note:** Current measurement is interpreter simulation (no real execution).  
Wave 5 will integrate hardware perf counters for validation.

---

## Cache Performance

### Sequential Access (Baseline)

| Level | Size | Cycles/Element | Expected | Status |
|-------|------|----------------|----------|--------|
| L1 | 16 KB | ${L1_SEQ_CYCLES:-N/A} | ~2-4 | $(if (( $(echo "${L1_SEQ_CYCLES:-99} < 5" | bc -l) )); then echo "🟢"; else echo "🟡"; fi) |
| L2 | 512 KB | - | ~10-15 | 🔴 |
| L3 | 16 MB | - | ~30-50 | 🔴 |

### Random Access (Cache Thrashing)

| Level | Size | Cycles/Access | Expected | Gap vs Sequential |
|-------|------|---------------|----------|-------------------|
| L1 | 16 KB | ${L1_RAND_CYCLES:-N/A} | ~8-15 | $(if [[ -n "$L1_SEQ_CYCLES" && -n "$L1_RAND_CYCLES" ]]; then echo "$(echo "scale=1; $L1_RAND_CYCLES / $L1_SEQ_CYCLES" | bc)x"; else echo "N/A"; fi) |
| L2 | 512 KB | - | ~15-30 | - |
| L3 | 16 MB | - | ~40-80 | - |

**Key Insight:** Random access is ~$(if [[ -n "$L1_SEQ_CYCLES" && -n "$L1_RAND_CYCLES" ]]; then echo "$(echo "scale=0; $L1_RAND_CYCLES / $L1_SEQ_CYCLES" | bc)x"; else echo "4-8x"; fi) slower than sequential.  
vTPU's phext-native addressing exploits dimensional locality to approach sequential performance.

